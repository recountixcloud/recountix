  const originalText = new WeakMap();
  const originalAttr = new WeakMap();
  let lang = localStorage.getItem(STORE) || "en";
  let applying = false;

  function normalize(value) {
    return String(value || "")
      .replace(/[\u2018\u2019]/g, "'")
      .replace(/[\u201C\u201D]/g, '"')
      .replace(/\s+/g, " ")
      .trim();
  }

  function preserveCase(source, translated) {
    if (!translated) return translated;
    if (source === source.toUpperCase() && /[A-Z]/.test(source)) return translated.toUpperCase();
    return translated;
  }

  function escapeRegExp(value) {
    return String(value).replace(/[\\^$.*+?()[\]{}|]/g, "\\$&");
  }

  function phraseFallback(raw, table) {
    let out = raw;
    const keys = Object.keys(table)
      .filter(key => key.length >= 3 && /[A-Za-z]/.test(key))
      .sort((a, b) => b.length - a.length);
    for (const key of keys) {
      if (!out.toLowerCase().includes(key.toLowerCase())) continue;
      out = out.replace(new RegExp(escapeRegExp(key), "gi"), match => preserveCase(match, table[key]));
    }
    return out;
  }

  function wordFallback(raw, table) {
    const words = [
      "Dashboard","Customer","Customers","Recovery","Report","Reports","Setting","Settings","Backup","Business","Businesses",
      "Payment","Payments","Amount","Pending","Total","Today","Date","Mobile","Name","Address","Status","Active","Inactive",
      "Save","Update","Delete","Add","Edit","View","Search","Select","Print","Download","Upload","Restore","History","Details",
      "Summary","Management","Records","Entry","Entries","Collection","Reminder","Follow-up","Executive","User","Admin","Staff"
    ];
    let out = raw;
    for (const word of words) {
      const translated = table[word] || table[word + "s"];
      if (!translated) continue;
      out = out.replace(new RegExp("\\b" + escapeRegExp(word) + "\\b", "gi"), match => preserveCase(match, translated));
    }
    return out;
  }

  function lookup(value) {
    const table = dict[lang];
    if (!table || lang === "en") return value;
    const raw = normalize(value);
    if (!raw) return value;

    const leadingIcon = raw.match(/^([✅✔❌💬📍📜📞🔐🔴🟠🟡🟢☁]+)\s*(.+)$/);
    const icon = leadingIcon ? leadingIcon[1] + " " : "";
    const text = leadingIcon ? leadingIcon[2] : raw;

    const punct = text.match(/^(.+?)([:：])$/);
    const core = punct ? punct[1].trim() : text;
    const suffix = punct ? punct[2] : "";

    let translated = table[text] || table[core];
    if (!translated) {
      const lowerKey = Object.keys(table).find(key => key.toLowerCase() === core.toLowerCase());
      translated = lowerKey ? table[lowerKey] : "";
    }
    if (translated) return icon + preserveCase(core, translated) + suffix;

    const partial = phraseFallback(core, table);
    if (partial !== core) return icon + partial + suffix;

    const wordLevel = wordFallback(core, table);
    if (wordLevel !== core) return icon + wordLevel + suffix;
    return value;
  }

  function translateTextNode(node) {
    const parent = node.parentElement;
    if (!parent) return;
    if (parent.closest(".rx-lang-switch, script, style, noscript, iframe, code, pre")) return;

    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    const base = originalText.get(node);
    const translated = lookup(base);
    node.nodeValue = base.replace(/\S[\s\S]*\S|\S/, translated);
  }

  function translateAttrs(el) {
    if (!el || el.closest(".rx-lang-switch, script, style, noscript, iframe, code, pre")) return;
    ["placeholder", "title", "aria-label", "alt", "value"].forEach(attr => {
      if (!el.hasAttribute(attr)) return;
      if (attr === "value" && !["button", "submit", "reset"].includes((el.getAttribute("type") || "").toLowerCase())) return;

      let map = originalAttr.get(el);
      if (!map) {
        map = {};
        originalAttr.set(el, map);
      }
      if (!(attr in map)) map[attr] = el.getAttribute(attr);
      el.setAttribute(attr, lookup(map[attr]));
    });
  }

  function walk(root) {
    if (!root) return;
    if (root.nodeType === Node.TEXT_NODE) {
      translateTextNode(root);
      return;
    }
    if (root.nodeType === Node.ELEMENT_NODE) translateAttrs(root);

    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
    let node;
    while ((node = walker.nextNode())) {
      if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
      else translateAttrs(node);
    }
  }

  function refreshSwitch() {
    document.querySelectorAll(".rx-lang-switch button").forEach(btn => {
      btn.classList.toggle("active", btn.dataset.lang === lang);
      btn.setAttribute("aria-pressed", String(btn.dataset.lang === lang));
    });
  }

  function addSwitch() {
    // Language preferences are available only inside Settings.
    if (!/\/settings\.html$/i.test(window.location.pathname)) return;
    if (document.querySelector(".rx-lang-switch")) return;
    const main = document.querySelector("main.main-content");
    if (!main) return;
    const section = document.createElement("section");
    section.className = "table-section fade";
    section.id = "languagePreferences";
    section.innerHTML = '<div class="summary-bar"><div><h2>Language</h2><span>Choose Language</span></div></div>';
    const wrap = document.createElement("div");
    wrap.className = "rx-lang-switch";
    wrap.setAttribute("role", "group");
    wrap.setAttribute("aria-label", "Language");
    wrap.innerHTML = Object.entries(LANGS)
      .map(([code, label]) => '<button type="button" data-lang="' + code + '">' + label + '</button>')
      .join("");
    section.appendChild(wrap);
    const topbar = main.querySelector(".topbar");
    if (topbar) topbar.insertAdjacentElement("afterend", section);
    else main.prepend(section);

    const style = document.createElement("style");
    style.textContent = `
      .rx-lang-switch{display:flex;flex-wrap:wrap;gap:8px;padding:8px 0}
      .rx-lang-switch button{border:1px solid #1A3D63;background:transparent;color:#1A3D63;font-weight:700;font-size:14px;padding:10px 18px;border-radius:10px;cursor:pointer}
      .rx-lang-switch button.active{background:#1A3D63;color:#fff}
      .rx-lang-switch button:focus-visible{outline:3px solid #38bdf8;outline-offset:3px}
    `;
    document.head.appendChild(style);

    wrap.addEventListener("click", event => {
      const btn = event.target.closest("button[data-lang]");
      if (btn) setLang(btn.dataset.lang);
    });
    refreshSwitch();
  }

  function applyLanguage() {
    if (applying) return;
    applying = true;
    walk(document.body);
    refreshSwitch();
    applying = false;
  }

  function setLang(next) {
    lang = next || "en";
    localStorage.setItem(STORE, lang);
    applyLanguage();
  }

  window.RecountixI18n = { setLang, applyLanguage, lookup };

  document.addEventListener("DOMContentLoaded", () => {
    addSwitch();
    applyLanguage();
    const observer = new MutationObserver(records => {
      if (applying || lang === "en") return;
      records.forEach(record => {
        record.addedNodes.forEach(node => {
          if (node.nodeType === Node.ELEMENT_NODE || node.nodeType === Node.TEXT_NODE) walk(node);
        });
      });
    });
    observer.observe(document.body, { childList: true, subtree: true });
  });
